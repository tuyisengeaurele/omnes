#!/usr/bin/env node
/**
 * Commit message policy.
 *
 * Two jobs. Enforce conventional commit format, and make it impossible to
 * attach a tool attribution trailer to a commit in this repo. The second one is
 * a hard project rule, so it belongs in a hook rather than in a reviewer's head.
 */

import { readFileSync } from 'node:fs';
import process from 'node:process';

const TYPES = [
  'feat',
  'fix',
  'refactor',
  'chore',
  'test',
  'docs',
  'perf',
  'build',
  'ci',
  'style',
  'revert',
];

const SUBJECT_RE = new RegExp(`^(${TYPES.join('|')})(\\([a-z0-9.-]+\\))?!?: .+`);
const MAX_SUBJECT = 72;
const MAX_BODY_LINE = 100;

/** Attribution trailers and tool signatures. None of these belong in this history. */
const FORBIDDEN = [
  { re: /co-?authored-?by:.*(claude|anthropic|openai|gpt|copilot|cursor|codex|bot)/i, what: 'tool attribution trailer' },
  { re: /generated\s+with\s+\[?(claude|chatgpt|copilot|cursor)/i, what: 'tool attribution line' },
  { re: /\bclaude(\s+code)?\b/i, what: 'assistant name' },
  { re: /\banthropic\b/i, what: 'vendor name' },
  { re: /\bai[- ]generated\b/i, what: 'generated-content marker' },
  { re: /\bnoreply@anthropic\.com\b/i, what: 'tool attribution address' },
  { re: /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/u, what: 'emoji' },
];

function main() {
  const path = process.argv[2];
  if (!path) {
    console.error('commit-msg: no message file given');
    return 1;
  }

  const all = readFileSync(path, 'utf8').split(/\r?\n/);
  const lines = all.filter((l) => !l.startsWith('#'));
  while (lines.length && lines[lines.length - 1].trim() === '') lines.pop();

  const errors = [];
  const subject = lines[0] ?? '';

  // A merge or revert commit generated by git keeps its own format.
  if (/^(Merge|Revert)\s/.test(subject)) return 0;

  if (!SUBJECT_RE.test(subject)) {
    errors.push(
      `subject must be "type(scope): description"\n    got: ${JSON.stringify(subject)}\n    types: ${TYPES.join(', ')}`
    );
  }
  if (subject.length > MAX_SUBJECT) {
    errors.push(`subject is ${subject.length} chars, limit is ${MAX_SUBJECT}`);
  }
  if (subject.endsWith('.')) {
    errors.push('subject must not end with a period');
  }
  const afterColon = subject.slice(subject.indexOf(': ') + 2);
  if (afterColon && afterColon[0] !== afterColon[0].toLowerCase()) {
    errors.push('subject description should start lowercase');
  }
  if (lines.length > 1 && lines[1].trim() !== '') {
    errors.push('leave a blank line between the subject and the body');
  }

  lines.forEach((line, i) => {
    // A long line with no spaces is a URL or a path and cannot be wrapped.
    if (i > 0 && line.length > MAX_BODY_LINE && line.includes(' ')) {
      errors.push(`body line ${i + 1} is ${line.length} chars, wrap at ${MAX_BODY_LINE}`);
    }
    for (const { re, what } of FORBIDDEN) {
      if (re.test(line)) errors.push(`line ${i + 1} contains a ${what}: ${line.trim().slice(0, 70)}`);
    }
  });

  if (errors.length === 0) return 0;

  console.error('\ncommit message rejected\n');
  errors.forEach((e) => console.error(`  ${e}`));
  console.error('');
  return 1;
}

process.exit(main());
